// Bundles the whole CLI into plugin/crashlens.mjs so the agent plugin works
// right after install with only Node.js: no npm install, no build step.
// The Anthropic SDK is left out (agents don't need --ai; it loads lazily).
// Run: npm run build:plugin. CI fails if the committed bundle is stale.
import { build } from "esbuild";
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const { version } = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));

await build({
  entryPoints: [join(root, "src", "cli.ts")],
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node22",
  external: ["@anthropic-ai/sdk"],
  banner: { js: `// crashlens ${version}, bundled for the agent plugin. Generated by scripts/build-plugin.mjs; do not edit.` },
  outfile: join(root, "plugin", "crashlens.mjs"),
  logLevel: "warning",
});
console.log("built plugin/crashlens.mjs");
