import type Anthropic from "@anthropic-ai/sdk";
import { renderIssueMarkdown, type Issue } from "./issue.js";
import { err, ok, type Result } from "./result.js";

export const DEFAULT_AI_MODEL = "claude-opus-5-5";

const SYSTEM = `You help a developer understand and fix a failure in their own program.

You receive a crashlens report: the crash or exception, the stack trace (frames in the developer's code are marked), and when available the failing source lines, recent git history and the log lines printed just before the failure.

Explain what most likely went wrong and propose a fix. Ground every claim in the report; when something can't be determined from it, say what to check instead of guessing. Prefer the smallest change that fixes the root cause, and show it as a diff or code snippet when the relevant code is in the report.

Reply in GitHub-flavored Markdown with these sections:
### What happened
### Why
### Suggested fix
### How to verify`;

export interface AiSuggestion {
  readonly model: string;
  readonly markdown: string;
}

/**
 * Ask Claude for an explanation and fix. Only the rendered report is sent:
 * the same Markdown the user can read, including any code snippets and log
 * lines in it. Callers must get the user's explicit consent first.
 */
export async function suggestFix(
  issue: Issue,
  options: { readonly client?: Anthropic; readonly model?: string } = {},
): Promise<Result<AiSuggestion>> {
  // Loaded on demand: the bundled agent plugin ships without the SDK, and
  // nothing else needs it.
  let sdk: typeof Anthropic;
  try {
    sdk = (await import("@anthropic-ai/sdk")).default;
  } catch {
    return err("rea_unavailable", "The Anthropic SDK is not installed. Run npm install in crashlens to use --ai.");
  }
  const client = options.client ?? new sdk();
  const model = options.model ?? process.env["CRASHLENS_AI_MODEL"] ?? DEFAULT_AI_MODEL;
  try {
    const response = await client.beta.messages.create({
      model,
      max_tokens: 16000,
      system: SYSTEM,
      output_config: { effort: "medium" },
      // If the model declines (safety classifier), let the API retry on a
      // suitable fallback model instead of returning nothing.
      betas: ["server-side-fallback-2026-07-01"],
      fallbacks: "default",
      messages: [{ role: "user", content: renderIssueMarkdown(issue) }],
    });
    if (response.stop_reason === "refusal")
      return err("rea_failed", "The model declined to answer for this report.");
    const text = response.content
      .flatMap((block) => (block.type === "text" ? [block.text] : []))
      .join("\n")
      .trim();
    if (text === "") return err("unexpected_rea_output", "The model returned no text.");
    return ok({ model: response.model, markdown: text });
  } catch (error) {
    return err("rea_unavailable", describeError(error, sdk));
  }
}

function describeError(error: unknown, Anthropic: typeof import("@anthropic-ai/sdk").default): string {
  if (error instanceof Anthropic.AuthenticationError)
    return "Anthropic API credentials were rejected. Check ANTHROPIC_API_KEY.";
  if (error instanceof Anthropic.PermissionDeniedError)
    return "This API key isn't allowed to use the model. Set CRASHLENS_AI_MODEL to one it can use.";
  if (error instanceof Anthropic.RateLimitError) return "Rate limited by the Anthropic API; try again shortly.";
  if (error instanceof Anthropic.APIConnectionError) return "Could not reach the Anthropic API.";
  if (error instanceof Anthropic.APIError) return `Anthropic API error ${error.status}: ${error.message}`;
  if (error instanceof Error && /api key|apiKey|authentication/i.test(error.message))
    return "No Anthropic API credentials found. Set ANTHROPIC_API_KEY to use --ai.";
  return error instanceof Error ? error.message : String(error);
}

/** Append the suggestion to an issue, clearly labeled as AI-generated. */
export function withSuggestion(issue: Issue, suggestion: AiSuggestion): Issue {
  return {
    ...issue,
    sections: [
      ...issue.sections,
      {
        heading: `AI suggestion (${suggestion.model}, verify before applying)`,
        kind: "markdown",
        markdown: suggestion.markdown,
      },
    ],
    evidence: [...issue.evidence, `AI suggestion: generated by ${suggestion.model} from this report only`],
  };
}
