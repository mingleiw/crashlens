import { createHash } from "node:crypto";
/** Last path element for POSIX and Windows paths alike, so signatures match across machines. */
function basename(path: string): string {
  return path.split(/[\\/]/).pop() ?? path;
}
import type { FailureFrame, FailureLanguage, ParsedFailure } from "./failure.js";
import type { Issue, IssueLocation, IssueSection } from "./issue.js";
import { classifyFailure } from "./rules.js";

const LANGUAGE: Readonly<Record<FailureLanguage, string>> = {
  go: "Go",
  rust: "Rust",
  python: "Python",
  java: "Java",
  node: "Node.js",
  sanitizer: "Sanitizer",
};

const SOURCE: Readonly<Record<FailureLanguage, Issue["source"]>> = {
  go: "go-panic",
  rust: "rust-panic",
  python: "python-exception",
  java: "java-exception",
  node: "node-exception",
  sanitizer: "sanitizer",
};

/** How many log lines before the failure to show. */
const LOG_CONTEXT_LINES = 15;

/** Express parsed failure output (panic, exception, sanitizer report) as an Issue. */
export function toFailureIssue(failure: ParsedFailure, input: string, text: string): Issue {
  const classification = classifyFailure(failure);
  const own = failure.frames.filter((f) => f.own && !f.createdBy);
  const first = own[0] ?? null;
  const place = first ?? failure.frames.find((f) => !f.createdBy) ?? null;
  const locationText =
    failure.location === null
      ? null
      : `${failure.location.file}:${failure.location.line}${failure.location.column === null ? "" : `:${failure.location.column}`}`;
  const where =
    place !== null
      ? place.function
      : failure.location !== null
        ? `${failure.location.file}:${failure.location.line}`
        : null;
  const sourceLine =
    locationText ?? (first !== null && first.file !== null ? `${first.file}:${first.line}` : null);
  const language = LANGUAGE[failure.language];

  const sections: IssueSection[] = [];
  if (failure.frames.length > 0)
    sections.push({
      heading: "Stack trace",
      kind: "code",
      language: "",
      lines: [...stackLines(failure.frames), "", "→ marks frames in your code"],
    });
  for (const stack of failure.extraStacks)
    sections.push({
      heading: upperFirst(stack.title || "Related stack"),
      kind: "code",
      language: "",
      lines: stackLines(stack.frames),
    });
  const logs = logContext(text, failure.start);
  if (logs.length > 0)
    sections.push({
      heading: "Log lines before the failure",
      kind: "code",
      language: "",
      lines: logs,
    });

  return {
    source: SOURCE[failure.language],
    kind: classification.kind,
    title: classification.title,
    where,
    summary: `${summaryLead(failure)}: **${lowerFirst(classification.title)}**${where === null ? "" : ` in \`${where}\``}${sourceLine === null || where === sourceLine ? "" : ` (\`${sourceLine}\`)`}. ${classification.explanation}`,
    facts: [
      { label: "Language", value: language },
      ...(failure.errorType === null || failure.language === "sanitizer"
        ? []
        : [{ label: "Exception", value: `\`${failure.errorType}\`` }]),
      ...(failure.language === "sanitizer" ? [{ label: "Tool", value: failure.header }] : []),
      { label: "Message", value: code(truncate(failure.message, 240)) },
      ...(failure.wrappedBy.length === 0
        ? []
        : [{ label: "Wrapped by", value: failure.wrappedBy.map((w) => code(truncate(w, 120))).join(" ← ") }]),
      ...(failure.context === null ? [] : [{ label: contextLabel(failure.language), value: code(failure.context) }]),
      ...(sourceLine === null ? [] : [{ label: "Source", value: code(sourceLine) }]),
      ...(failure.signal === null ? [] : [{ label: "Signal", value: code(failure.signal.replace(/^\[|\]$/g, "")) }]),
    ],
    sections,
    locations: locations(failure),
    cause: classification.explanation,
    message: failure.errorType === null ? failure.message : `${failure.errorType}: ${failure.message}`,
    nextSteps: classification.nextSteps,
    confidence: classification.confidence,
    warnings: warnings(failure, own.length),
    evidence: [
      `Input: \`${input}\` (sha256 \`${createHash("sha256").update(text).digest("hex")}\`)`,
      `Parsed as ${language} ${failure.header} output; ${failure.frames.length} frame${failure.frames.length === 1 ? "" : "s"}, ${own.length} in your code.`,
    ],
    limitations: [
      "Parsed from text output only; no binary or core dump was examined.",
      "\"Your code\" is decided by package, module or file path, not by build metadata.",
    ],
    signature: signature(failure, classification.kind, own),
    footer: "Generated by crashlens from failure output; the program was not executed.",
  };
}

function summaryLead(failure: ParsedFailure): string {
  const language = LANGUAGE[failure.language];
  switch (failure.language) {
    case "go":
      return `A Go program ${failure.header === "fatal error" ? "hit a fatal runtime error" : "panicked"}`;
    case "rust":
      return "A Rust program panicked";
    case "sanitizer":
      return `${failure.header} found a bug`;
    default:
      return `A ${language} program raised an uncaught exception`;
  }
}

function contextLabel(language: FailureLanguage): string {
  return language === "go" ? "Goroutine" : language === "sanitizer" ? "Access" : "Thread";
}

function warnings(failure: ParsedFailure, ownFrames: number): string[] {
  const list: string[] = [];
  if (failure.frames.length === 0)
    list.push(
      failure.language === "rust"
        ? "No stack trace in the output. Rerun with `RUST_BACKTRACE=1` to see which functions led here."
        : failure.language === "sanitizer"
          ? "No stack trace in the report. For UBSan, set `UBSAN_OPTIONS=print_stacktrace=1`."
          : "No stack trace in the output; only the message was available.",
    );
  else if (ownFrames === 0)
    list.push("None of the frames look like your code (all runtime, standard library or dependencies).");
  if (failure.otherGoroutines > 0)
    list.push(
      `Only the failing goroutine is shown; ${failure.otherGoroutines} other goroutine${failure.otherGoroutines === 1 ? " was" : "s were"} in the output.`,
    );
  return list;
}

/** Runtime frames after the last own frame beyond this many are summarized in one line. */
const TRAILING_FRAMES = 1;

function stackLines(frames: readonly FailureFrame[]): string[] {
  const lastOwn = frames.findLastIndex((f) => f.own && !f.createdBy);
  const keep = lastOwn === -1 ? frames.length : lastOwn + 1 + TRAILING_FRAMES;
  // Go's "created by" frame says where the goroutine started: always shown.
  const hidden = frames.filter((f, index) => index >= keep && !f.createdBy).length;
  const shown = hidden <= 1 ? frames.map((f, index) => [f, index] as const) : frames.flatMap((f, index) => (index < keep || f.createdBy ? [[f, index] as const] : []));
  const lines = shown.flatMap(([f, index]) => {
    const marker = f.own && !f.createdBy ? "→" : " ";
    const name = f.createdBy ? `created by ${f.function}` : f.function;
    const at =
      f.file === null ? "" : `  at ${f.file}:${f.line}${f.column === null ? "" : `:${f.column}`}`;
    const line = `${marker} #${index} ${name}${at}`;
    return f.code === null ? [line] : [line, `       ${f.code}`];
  });
  return hidden <= 1 ? lines : [...lines, `  … ${hidden} more frames in runtime or library code`];
}

/** Last lines before the failure output: what the program logged just before it died. */
export function logContext(text: string, start: number): string[] {
  const lines = text
    .slice(0, start)
    .split("\n")
    .map((line) => line.trimEnd())
    .filter((line) => line !== "");
  return lines.slice(-LOG_CONTEXT_LINES).map((line) => truncate(line, 300));
}

/** Code locations a person would open, own frames first. */
function locations(failure: ParsedFailure): IssueLocation[] {
  const withFile = failure.frames.filter((f) => f.file !== null && f.line !== null && !f.createdBy);
  return [...withFile.filter((f) => f.own), ...withFile.filter((f) => !f.own)].map((f) => ({
    file: f.file as string,
    line: f.line as number,
    ...(f.column === null ? {} : { column: f.column }),
    ...(f.locals === undefined ? {} : { locals: f.locals }),
    function: f.function,
    own: f.own,
  }));
}

/**
 * Crash kind + top three frames in the user's code. Qualified names (Go,
 * Rust, Java) stand alone; elsewhere the file name is added because names
 * like `main` repeat. Directories are never included: they differ between
 * machines. Without frames, the runtime-reported file name and line is used.
 */
function signature(failure: ParsedFailure, kind: string, own: readonly FailureFrame[]): string {
  const qualified = failure.language === "go" || failure.language === "rust" || failure.language === "java";
  const parts =
    own.length > 0
      ? own
          .slice(0, 3)
          .map((f) => (qualified || f.file === null ? f.function : `${basename(f.file)}:${f.function}`))
      : failure.location !== null
        ? [`${basename(failure.location.file)}:${failure.location.line}`]
        : [];
  return createHash("sha256").update([kind, ...parts].join("|")).digest("hex").slice(0, 12);
}

/** "Nil pointer" → "nil pointer", but keep names like "RefCell" or "NULL" intact. */
function lowerFirst(text: string): string {
  return /^[A-Z][a-z]/.test(text) ? text.charAt(0).toLowerCase() + text.slice(1) : text;
}

function upperFirst(text: string): string {
  return text.charAt(0).toUpperCase() + text.slice(1);
}

/** Inline code that survives backticks inside the text. */
export function code(text: string): string {
  return text.includes("`") ? `\`\` ${text} \`\`` : `\`${text}\``;
}

function truncate(text: string, max: number): string {
  const single = text.replace(/\s+/g, " ");
  return single.length > max ? `${single.slice(0, max - 1)}…` : single;
}
