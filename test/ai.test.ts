import Anthropic from "@anthropic-ai/sdk";
import assert from "node:assert/strict";
import { createServer, type IncomingHttpHeaders } from "node:http";
import type { AddressInfo } from "node:net";
import { after, before, describe, it } from "node:test";
import { suggestFix, withSuggestion } from "../src/ai.js";
import { renderIssueMarkdown, type Issue } from "../src/issue.js";

/** A stand-in for the Messages API that records requests and replays canned answers. */
let reply: { status: number; body: unknown } = { status: 200, body: {} };
const seen: { headers: IncomingHttpHeaders; body: Record<string, unknown> }[] = [];
const fake = createServer((req, res) => {
  const chunks: Buffer[] = [];
  req.on("data", (c: Buffer) => chunks.push(c));
  req.on("end", () => {
    seen.push({ headers: req.headers, body: JSON.parse(Buffer.concat(chunks).toString("utf8")) });
    res.writeHead(reply.status, { "Content-Type": "application/json" });
    res.end(JSON.stringify(reply.body));
  });
});
let client: Anthropic;
before(async () => {
  await new Promise<void>((resolve) => fake.listen(0, "127.0.0.1", resolve));
  client = new Anthropic({ apiKey: "test-key", baseURL: `http://127.0.0.1:${(fake.address() as AddressInfo).port}`, maxRetries: 0 });
});
after(() => fake.close());

const issue: Issue = {
  source: "python-exception", kind: "python-none", title: "Value was None", where: "total",
  summary: "A Python program raised an uncaught exception.", facts: [], sections: [], locations: [],
  cause: "The code used None.", nextSteps: [], confidence: "high", warnings: [], evidence: [],
  limitations: [], signature: "1cf6e3ddfe8e", footer: "",
};

function message(fields: Record<string, unknown>) {
  return {
    id: "msg_1", type: "message", role: "assistant", model: "claude-opus-5-5",
    content: [], stop_reason: "end_turn", stop_sequence: null,
    usage: { input_tokens: 10, output_tokens: 20 }, ...fields,
  };
}

describe("suggestFix", () => {
  it("sends only the rendered report, with fallbacks enabled, and returns the answer", async () => {
    reply = { status: 200, body: message({ content: [{ type: "text", text: "### What happened\nLoad returned None." }] }) };
    const result = await suggestFix(issue, { client });
    assert.ok(result.ok);
    assert.equal(result.value.markdown, "### What happened\nLoad returned None.");

    const request = seen.at(-1);
    assert.ok(request);
    assert.equal(request.body["model"], "claude-opus-5-5");
    assert.equal(request.body["fallbacks"], "default");
    assert.deepEqual(request.body["output_config"], { effort: "medium" });
    assert.match(String(request.headers["anthropic-beta"]), /server-side-fallback-2026-07-01/);
    assert.deepEqual(request.body["messages"], [{ role: "user", content: renderIssueMarkdown(issue) }]);
    assert.equal(request.body["thinking"], undefined);
  });

  it("reports refusals and API errors instead of throwing", async () => {
    reply = { status: 200, body: message({ stop_reason: "refusal", stop_details: { type: "refusal", category: null, explanation: null } }) };
    const refused = await suggestFix(issue, { client });
    assert.equal(refused.ok, false);
    if (!refused.ok) assert.match(refused.error.message, /declined/);

    reply = { status: 401, body: { type: "error", error: { type: "authentication_error", message: "invalid x-api-key" } } };
    const denied = await suggestFix(issue, { client });
    assert.equal(denied.ok, false);
    if (!denied.ok) assert.match(denied.error.message, /credentials were rejected/);
  });

  it("labels the suggestion as AI-generated in the report", () => {
    const updated = withSuggestion(issue, { model: "claude-opus-5-5", markdown: "### Why\nBecause." });
    const markdown = renderIssueMarkdown(updated);
    assert.match(markdown, /## AI suggestion \(claude-opus-5-5, verify before applying\)\n\n### Why\nBecause\./);
    assert.match(updated.evidence.at(-1) ?? "", /generated by claude-opus-5-5 from this report only/);
  });
});
